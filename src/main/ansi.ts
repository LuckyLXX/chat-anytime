/**
 * ANSI/控制序列剥离：把 PTY / SSH 的原始字节流变成人能读的文本。
 *
 * 从 `ssh-connections.ts` 抽出来的单一实现（原来是那里的私有导出）：现在终端侧
 * 也要用它——服务型作品「起不来」的提示里带的是启动命令的输出尾部，而 ConPTY 的
 * 回显里塞满了光标可见性/标题栏序列（真机实测 2026-09-23：toast 里显示的是
 * `…D␦D␦[25h🫧 Jev 潜台词读心器[25h…` 这种噪声，完全没法看）。
 *
 * 剥三类：OSC（`ESC ] … BEL/ST`）、CSI（`ESC [ 参数 中间 终止`）、以及除
 * `\t\n\r` 之外的控制字符。**不做换行/空格压缩**：那是调用方的事（提示类内容
 * 各自有自己的排版口径）。
 */
export function stripAnsi(text: string): string {
  return text
    .replace(/\u001b\][^\u0007\u001b]*(?:\u0007|\u001b\\)?/g, "")
    .replace(/\u001b\[[0-9;:?]*[ -/]*[@-~]/g, "")
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, "");
}
